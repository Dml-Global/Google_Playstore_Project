CREATE VIEW App_Analysis_View AS

SELECT
    App,
    Category,
    Rating,
    Reviews,
    Size,
    Installs,
    Type,
    Price,
    Content_Rating,
    Genres,
    Last_Updated,
    Android_Ver
FROM dbo.Apps;
SELECT *
FROM App_Analysis_View;