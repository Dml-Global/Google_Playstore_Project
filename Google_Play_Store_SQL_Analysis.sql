/* Question 1:
Which apps have the highest rating in the available dataset?
*/

SELECT DISTINCT
    App,
    Rating
FROM dbo.Apps
WHERE Rating = (
    SELECT MAX(Rating)
    FROM dbo.Apps
)
ORDER BY App;
/* Question 2:
What are the number of installs and reviews for the highest-rated apps?
Return the apps with the highest reviews at the top.
*/

SELECT DISTINCT
    App,
    Rating,
    Reviews,
    Installs
FROM dbo.Apps
WHERE Rating = (
    SELECT MAX(Rating)
    FROM dbo.Apps
)
ORDER BY Reviews DESC;
/* Question 3:
Which app has the highest number of reviews?
Also show the number of reviews and its category.
*/

SELECT DISTINCT
    App,
    Reviews,
    Category
FROM dbo.Apps
WHERE Reviews = (
    SELECT MAX(Reviews)
    FROM dbo.Apps
);
SELECT MAX(Reviews) AS HighestReviewCount
FROM dbo.Apps;
/* Question 4:
What is the total amount of revenue generated by the Google Play Store
from paid app purchases?

Assumption:
Revenue = Price × Number of Installs
*/

SELECT
    SUM(Price * Installs) AS TotalRevenue
FROM dbo.Apps
WHERE Price > 0;
/* Question 5:
Which category has the highest total number of installs?
Also show the total installs for that category.
*/

SELECT TOP 1 WITH TIES
    Category,
    SUM(Installs) AS TotalInstalls
FROM dbo.Apps
GROUP BY Category
ORDER BY SUM(Installs) DESC;
/* Question 6:
Which genre has the highest number of published apps?
*/

SELECT TOP 1 WITH TIES
    Genres,
    COUNT(DISTINCT App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Genres
ORDER BY COUNT(DISTINCT App) DESC;
SELECT
    Genres,
    COUNT(DISTINCT App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Genres
ORDER BY NumberOfApps DESC;
/* Question 7:
Provide the list of all games ordered so that the game
with the highest number of installs appears at the top.
Use DISTINCT to avoid duplicate results.
*/

SELECT DISTINCT
    App,
    Installs
FROM dbo.Apps
WHERE Category = 'GAME'
ORDER BY Installs DESC;
/* Question 8:
Provide the list of apps that can work on
Android version 4.0.3 and up.
*/

SELECT DISTINCT
    App,
    Android_Ver
FROM dbo.Apps
WHERE Android_Ver = '4.0.3 and up'
ORDER BY App;
SELECT
    COUNT(DISTINCT App) AS NumberOfApps
FROM dbo.Apps
WHERE Android_Ver = '4.0.3 and up';
/* Question 9:
Count the number of Free and Paid apps.
*/

SELECT
    Type,
    COUNT(DISTINCT App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Type;
/* Question 10:
Find the category with the highest average rating.
*/

SELECT TOP 10
    Category,
    AVG(Rating) AS AverageRating,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Category
ORDER BY AverageRating DESC;
/* Question 11:
Find the category with the highest total installs.
*/

SELECT TOP 10
    Category,
    SUM(Installs) AS TotalInstalls,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Category
ORDER BY TotalInstalls DESC;
/* Question 12:
Find the category with the highest average installs per app.
*/

SELECT TOP 10
    Category,
    AVG(Installs) AS AverageInstallsPerApp,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Category
ORDER BY AverageInstallsPerApp DESC;
/* Question 13:
Compare average installs by rating.
*/

SELECT
    Rating,
    AVG(Installs) AS AverageInstalls,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Rating
ORDER BY Rating DESC;
/* Question 14:
Find categories with the highest number of paid apps.
*/

SELECT TOP 10
    Category,
    COUNT(App) AS NumberOfPaidApps
FROM dbo.Apps
WHERE Type = 'Paid'
GROUP BY Category
ORDER BY NumberOfPaidApps DESC;
/* Question 15:
Find the most expensive paid apps.
*/

SELECT TOP 10
    App,
    Category,
    Price,
    Installs
FROM dbo.Apps
WHERE Type = 'Paid'
ORDER BY Price DESC;
/* Question 16:
Find categories with the highest number of free apps.
*/

SELECT TOP 10
    Category,
    COUNT(App) AS NumberOfFreeApps
FROM dbo.Apps
WHERE Type = 'Free'
GROUP BY Category
ORDER BY NumberOfFreeApps DESC;
/* Question 17:
Find categories with the highest number of paid apps.
*/

SELECT TOP 10
    Category,
    COUNT(App) AS NumberOfPaidApps
FROM dbo.Apps
WHERE Type = 'Paid'
GROUP BY Category
ORDER BY NumberOfPaidApps DESC;
/* Question 18:
Find categories with the highest average number of reviews.
*/

SELECT TOP 10
    Category,
    AVG(Reviews) AS AverageReviews,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Category
ORDER BY AverageReviews DESC;
/* Question 19:
Find categories with the highest average number of installs.
*/

SELECT TOP 10
    Category,
    AVG(Installs) AS AverageInstalls,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
GROUP BY Category
ORDER BY AverageInstalls DESC;
/* Question 20:
Find categories with the highest average rating
among apps with more than 100,000 installs.
*/

SELECT TOP 10
    Category,
    AVG(Rating) AS AverageRating,
    COUNT(App) AS NumberOfApps
FROM dbo.Apps
WHERE Installs >= 100000
GROUP BY Category
ORDER BY AverageRating DESC;
